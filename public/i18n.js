function chooseLocale() {
    try {
        const saved = localStorage.getItem('wapit.locale');

        if (saved && MESSAGES[saved]) return saved;
    } catch {
        // Storage can be unavailable in private windows; the browser language decides then.
    }

    const languages = navigator.languages?.length ? navigator.languages : [navigator.language ?? 'en'];

    return languages.some((language) => /^pt\b/i.test(language)) ? 'pt-BR' : 'en';
}

export const locale = chooseLocale();

export function t(key, values = {}) {
    const template = MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;

    return template.replace(/\{(\w+)\}/g, (whole, name) => (name in values ? String(values[name]) : whole));
}

export function plural(key, count, values = {}) {
    return t(`${key}.${count === 1 ? 'one' : 'other'}`, { count, ...values });
}

export function translatePage(root = document) {
    document.documentElement.lang = locale;

    for (const [attribute, apply] of [
        ['data-i18n', (element, text) => { element.textContent = text; }],
        ['data-i18n-placeholder', (element, text) => { element.placeholder = text; }],
        ['data-i18n-aria-label', (element, text) => { element.setAttribute('aria-label', text); }],
        ['data-i18n-title', (element, text) => { element.title = text; }],
    ]) {
        root.querySelectorAll(`[${attribute}]`).forEach((element) => apply(element, t(element.getAttribute(attribute))));
    }
}
